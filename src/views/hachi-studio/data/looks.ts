export interface Look {
  id: string
  name: string
  group: string
  note: string
  exposure: number
  contrast: number
  saturation: number
  warmth: number
  tint: number
  fade: number
}

function look(
  id: string,
  name: string,
  group: string,
  note: string,
  exposure = 0,
  contrast = 1,
  saturation = 1,
  warmth = 0,
  tint = 0,
  fade = 0,
): Look {
  return { id, name, group, note, exposure, contrast, saturation, warmth, tint, fade }
}

